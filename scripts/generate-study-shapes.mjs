#!/usr/bin/env node
/**
 * Emit the study record-kind shape tables, so both languages project from one
 * declaration.
 *
 * The classification in `src/study/registry.ts` is the single source, and
 * `tests/study-field-completeness.test.mjs` is what keeps it honest: it walks
 * each Zod schema and fails on any field the tables do not classify, in either
 * direction. A second, hand-maintained copy of those tables in Python would be a
 * second thing that can drift from the schemas, and the completeness test would
 * not be watching it -- so Python reads the emitted tables instead of restating
 * them.
 *
 * One copy is written, under `python/src/ketqat_runner/schemas/`, because that
 * is the only place the tables are read: the TypeScript side has them in code.
 * A second copy under `schemas/` would be 120 KB of the npm package that no npm
 * consumer reads, and the package has a size policy. Drift is caught instead by
 * `tests/study-field-completeness.test.mjs`, which re-serializes the registry
 * and compares the bytes -- a stronger check than comparing two emitted copies
 * to each other, since it compares the emitted copy to the source.
 */
import { writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

import { STUDY_HASH_LIMITS } from "../dist/study/limits.js"
import { STUDY_FIELD_CLASSES, STUDY_PURPOSE_FIELD_CLASSES } from "../dist/study/projection.js"
import { STUDY_RECORD_KINDS } from "../dist/study/registry.js"
import { STUDY_HASH_DOMAIN, STUDY_HASH_RULES_ID } from "../dist/study/rules.js"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")

/** A shape as plain data: the same tree, with no TypeScript types in it. */
function serializeValue(value) {
  if (value.kind === "leaf") return { kind: "leaf" }
  if (value.kind === "array") return { kind: "array", item: serializeValue(value.item) }
  return { kind: "object", shape: serializeShape(value.shape) }
}

function serializeShape(shape) {
  return {
    name: shape.name,
    fields: shape.fields.map((field) => ({
      name: field.name,
      field_class: field.field_class,
      value: serializeValue(field.value),
    })),
  }
}

const document = {
  note:
    "Generated by scripts/generate-study-shapes.mjs from src/study/registry.ts. " +
    "Do not hand-edit: the classification is checked against the Zod schemas by " +
    "tests/study-field-completeness.test.mjs, and a hand-edited copy is a copy that test is not watching.",
  hash_domain: STUDY_HASH_DOMAIN,
  hash_rules_id: STUDY_HASH_RULES_ID,
  field_classes: [...STUDY_FIELD_CLASSES],
  purpose_field_classes: STUDY_PURPOSE_FIELD_CLASSES.map((entry) => ({
    purpose: entry.purpose,
    classes: [...entry.classes],
    nested_classes: [...entry.nested_classes],
  })),
  limits: { ...STUDY_HASH_LIMITS },
  record_kinds: STUDY_RECORD_KINDS.map((entry) => ({
    record_kind: entry.record_kind,
    self_hash_field: entry.self_hash_field,
    self_hash_purpose: entry.self_hash_purpose,
    shape: serializeShape(entry.shape),
  })),
}

writeFileSync(
  resolve(root, "python", "src", "ketqat_runner", "schemas", "study-record-shapes.json"),
  `${JSON.stringify(document, null, 2)}\n`,
)
